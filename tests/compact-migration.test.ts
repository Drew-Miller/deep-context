import path from "node:path";
import os from "node:os";
import { createHash } from "node:crypto";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { mkdtemp, readFile, writeFile, mkdir, rm, realpath, readdir } from "node:fs/promises";
import { afterEach, describe, expect, it } from "vitest";
import { initProject } from "../src/projects/index.js";
import { legacyInitProject } from "./legacy-fixture.js";
import { migrateLayout, repairLayout } from "../src/migration/layout.js";
import { migrateFilenames } from "../src/migration/filenames.js";
import { captureBacklog, activateBacklog } from "../src/backlog/index.js";
import { canonicalRecordById } from "../src/core/records.js";
import { layoutPaths } from "../src/core/layout.js";
import { parseMarkdown, renderMarkdown } from "../src/frontmatter/index.js";
import { startMemoryTask, resolveMemoryTask } from "../src/tasks/memory.js";
import { validateProject } from "../src/validation/index.js";
const cleanup: string[] = [];
const exec = promisify(execFile);
afterEach(async()=>{for(const root of cleanup.splice(0)) await rm(root,{recursive:true,force:true});});
async function fixture(legacy=false) { const home=await realpath(await mkdtemp(path.join(os.tmpdir(),"compact-layout-")));cleanup.push(home); return (legacy?legacyInitProject:initProject)(home,{name:"fixture"}); }

describe("compact layout adoption",()=>{
  it("initializes compact storage and rejects hybrid canonical roots",async()=>{
    const root=await fixture();
    expect(layoutPaths(root).compact).toBe(true);
    for(const file of ["docs/architecture.md","work/INDEX.md","sources/INDEX.md"]) expect(await readFile(path.join(root,file),"utf8")).toBeTruthy();
    for(const file of ["doc","repo","START_HERE.md","docs/plan"]) await expect(readFile(path.join(root,file))).rejects.toMatchObject({code:"ENOENT"});
    expect(await validateProject(root)).toEqual([]);
    await mkdir(path.join(root,"doc"));
    expect(()=>layoutPaths(root)).toThrow("Mixed canonical layouts");
  });
  it("migrates paired objectives and preserves ownership, provenance and original hashes on repeat",async()=>{
    const root=await fixture(true);
    const task=await startMemoryTask(root,{chatId:"migration-chat",description:"Migrate owned execution"});
    const stateBefore=parseMarkdown(await readFile(path.join(task.taskPath,"TASK_STATE.md"),"utf8")).data;
    const item=await captureBacklog(root,{title:"Compact adoption",pitch:"One objective",provenance:"fixture"});
    const id=String(parseMarkdown(await readFile(item,"utf8")).data.id);
    const active=await activateBacklog(root,id,"Execute it",{tasks:[task.taskId]});
    const activeId=String(parseMarkdown(await readFile(active,"utf8")).data.id);
    const queued=parseMarkdown(await readFile(item,"utf8"));queued.data.status="planned";
    await writeFile(item,renderMarkdown(queued.data,queued.body));
    const source=path.join(root,"doc/sources/SRC-A.md");
    const sourceText=renderMarkdown({id:"SRC-A",path:"retired.txt",kind:"text",tracking:"not-applicable",disposition:"imported",reason:"Authored reason",origin:"confirmed",targets:[],sha256:"historical-hash"},"# Authored provenance\n\nPreserve interpretation.\n");
    await writeFile(source,sourceText);
    const historicalReport="# Earlier investigation\n\nThis conclusion remains historical evidence.\n";
    await writeFile(path.join(root,"doc/reports/earlier-investigation.md"),historicalReport);
    await mkdir(path.join(root,"docs/plan"),{recursive:true});
    await writeFile(path.join(root,"docs/plan/checkpoint.sha256"),"immutable snapshot\n");
    const preview=await migrateLayout(root); expect(preview.conflicts).toEqual([]);
    const result=await migrateLayout(root,{apply:true}); expect(result.applied).toBe(true);
    const current=await canonicalRecordById(path.join(root,"work/items"),activeId);
    expect(current).toBe(await canonicalRecordById(path.join(root,"work/items"),id));
    const work=parseMarkdown(await readFile(current!,"utf8"));expect(work.data.aliases).toContain(activeId);expect(work.body).toContain("Execute it");
    expect(work.data.status).toBe("active");
    expect(work.data.status_history).toEqual(expect.arrayContaining([expect.objectContaining({from:"planned",to:"active"})]));
    const resolved=await resolveMemoryTask(root,undefined,{chatId:"migration-chat"});expect(resolved.taskId).toBe(task.taskId);expect(resolved.ownerBindingId).toBe(task.ownerBindingId);expect(resolved.stateRevision).toBe(task.stateRevision);
    const stateAfter=parseMarkdown(await readFile(path.join(task.taskPath,"TASK_STATE.md"),"utf8")).data;
    expect(stateAfter.source_binding).toEqual(stateBefore.source_binding);
    const migratedSource=await canonicalRecordById(path.join(root,"sources/records"),"SRC-A");expect(await readFile(migratedSource!,"utf8")).toBe(sourceText);
    const archive=(result as {archive:string}).archive;
    const pathMap=JSON.parse(await readFile(path.join(root,archive,"path-map.json"),"utf8"));
    const migratedReport=parseMarkdown(await readFile(path.join(root,pathMap["doc/reports/earlier-investigation.md"]),"utf8"));
    expect(migratedReport.data).toMatchObject({title:"Earlier investigation",status:"historical",origin:"inferred",features:[]});
    expect(migratedReport.body).toContain(historicalReport.trim());
    expect(await readFile(path.join(root,archive,"original/doc/reports/earlier-investigation.md"),"utf8")).toBe(historicalReport);
    const hashes=JSON.parse(await readFile(path.join(root,archive,"hashes.json"),"utf8"));
    for(const [name,hash] of Object.entries(hashes)) expect(createHash("sha256").update(await readFile(path.join(root,archive,"original",name))).digest("hex")).toBe(hash);
    expect(await readFile(path.join(root,archive,"original/docs/plan/checkpoint.sha256"),"utf8")).toBe("immutable snapshot\n");
    expect((await migrateLayout(root,{apply:true})).alreadyCompact).toBe(true);
    expect(await validateProject(root)).toEqual([]);
  });
  it("repairs an interrupted layout journal and refuses intervening edits",async()=>{
    const root=await fixture(true);const result=await migrateLayout(root,{apply:true});
    const journalFile=path.join(root,".local/layout-operation.json");const journal=JSON.parse(await readFile(journalFile,"utf8"));
    journal.status="pending";await writeFile(journalFile,JSON.stringify(journal));
    const write=journal.writes.find((w:{path:string;after:unknown})=>w.path==="docs/architecture.md");
    await writeFile(path.join(root,write.path),"intervening edit");await expect(repairLayout(root)).rejects.toThrow("Recovery refuses changed file");
    await writeFile(path.join(root,write.path),write.after);await repairLayout(root);
    expect(JSON.parse(await readFile(journalFile,"utf8")).status).toBe("committed");expect(result.applied).toBe(true);
  });
  it("renames compact records with alias lookup, collision handling and no forwarding clutter",async()=>{
    const root=await fixture();const first=await captureBacklog(root,{title:"Old name",pitch:"Objective",provenance:"fixture"});
    const doc=parseMarkdown(await readFile(first,"utf8"));doc.data.title="New name";doc.data.aliases=["OLD-ID"];
    await writeFile(first,renderMarkdown(doc.data,doc.body));
    await captureBacklog(root,{title:"New name",pitch:"Another",provenance:"fixture"});
    const moved=await migrateFilenames(root,{id:"OLD-ID",apply:true});expect(moved.moves[0].to).toBe("work/items/new-name-2.md");
    await expect(readFile(first)).rejects.toMatchObject({code:"ENOENT"});expect(await canonicalRecordById(path.join(root,"work/items"),"OLD-ID")).toBe(path.join(root,moved.moves[0].to));
    expect(await validateProject(root)).toEqual([]);
  });
  it("distinguishes a migrated milestone label from a missing task UUID",async()=>{
    const root=await fixture();
    const file=await captureBacklog(root,{title:"Historical implementation",pitch:"Preserve a legacy milestone",provenance:"fixture"});
    const document=parseMarkdown(await readFile(file,"utf8"));
    document.data.prior_ledger_state="done";
    document.data.tasks=["DC-09"];
    await writeFile(file,renderMarkdown(document.data,document.body));
    let diagnostics=await validateProject(root);
    expect(diagnostics.some(item=>item.code==="historical-task-reference" && item.level==="warning")).toBe(true);
    expect(diagnostics.some(item=>item.code==="unknown-task")).toBe(false);
    document.data.tasks=["00000000-0000-0000-0000-000000000001"];
    await writeFile(file,renderMarkdown(document.data,document.body));
    diagnostics=await validateProject(root);
    expect(diagnostics.some(item=>item.code==="unknown-task" && item.level==="error")).toBe(true);
  });
  it("routes project-specific top-level docs and refuses stale source startup paths",async()=>{
    const home=await realpath(await mkdtemp(path.join(os.tmpdir(),"aftershock-like-layout-")));cleanup.push(home);
    const repository=path.join(home,"source repo");
    await exec("git",["init",repository]);
    await exec("git",["-C",repository,"config","user.name","Fixture"]);
    await exec("git",["-C",repository,"config","user.email","fixture@example.com"]);
    await mkdir(path.join(repository,"docs/plan"),{recursive:true});
    await writeFile(path.join(repository,"docs/plan/STATUS.json"),"{}\n");
    await writeFile(path.join(repository,"START_HERE.md"),"Read [.deep-context product](.deep-context/doc/PRODUCT.md).\n");
    await exec("git",["-C",repository,"add","."]);
    await exec("git",["-C",repository,"commit","-m","fixture"]);
    const root=await legacyInitProject(home,{name:"source-repo",repository});
    const sourceAgents=path.join(repository,"AGENTS.md");
    await writeFile(sourceAgents,(await readFile(sourceAgents,"utf8"))+"\nRead `.deep-context/doc/PRODUCT.md`.\n");
    await writeFile(path.join(root,"doc/PRODUCT.md"),"# Product\n\nRead [current status](repo/docs/plan/STATUS.json).\n");
    await writeFile(path.join(root,"doc/CONVERSION-MAP.md"),"# Conversion map\n\nSource schedule: `repo/docs/plan/STATUS.json`.\n");
    const contextAgents=path.join(root,"AGENTS.md");
    await writeFile(contextAgents,(await readFile(contextAgents,"utf8"))+"\nRead `doc/PRODUCT.md` and `repo/docs/plan/STATUS.json`.\n");
    const sourceFiles=await readdir(path.join(root,"doc/sources"));
    const sourceRecord=await Promise.all(sourceFiles.filter(name=>name.endsWith(".md")).map(async name=>({name,body:await readFile(path.join(root,"doc/sources",name),"utf8")})));
    const record=sourceRecord.find(entry=>entry.body.includes("path: docs/plan/STATUS.json"));
    expect(record).toBeDefined();
    const recordId=String(parseMarkdown(record!.body).data.id);
    await writeFile(path.join(root,"doc/sources",record!.name),record!.body+"\nSource route: `repo/docs/plan/STATUS.json`.\n");
    const unsafe=await migrateLayout(root);
    expect(unsafe.moves).toEqual(expect.arrayContaining([{from:"doc/PRODUCT.md",to:"docs/product.md"},{from:"doc/CONVERSION-MAP.md",to:"docs/conversion-map.md"}]));
    expect(unsafe.conflicts).toEqual(expect.arrayContaining([expect.stringContaining("AGENTS.md"),expect.stringContaining("START_HERE.md")]));
    await expect(migrateLayout(root,{apply:true})).rejects.toThrow("Source startup route must be updated");
    await writeFile(sourceAgents,(await readFile(sourceAgents,"utf8")).replaceAll(".deep-context/doc/PRODUCT.md",".deep-context/docs/product.md"));
    await writeFile(path.join(repository,"START_HERE.md"),"Read [.deep-context product](.deep-context/docs/product.md).\n");
    expect((await migrateLayout(root)).conflicts).toEqual([]);
    const migrated=await migrateLayout(root,{apply:true});expect(migrated.applied).toBe(true);
    expect(await readFile(path.join(root,"docs/product.md"),"utf8")).toContain("[current status](../../docs/plan/STATUS.json)");
    expect(await readFile(path.join(root,"docs/conversion-map.md"),"utf8")).toContain("`../docs/plan/STATUS.json`");
    expect(await readFile((await canonicalRecordById(path.join(root,"sources/records"),recordId))!,"utf8")).not.toContain("repo/");
    for(const name of ["AGENTS.md","CONTEXT_MAP.md"]) expect(await readFile(path.join(root,name),"utf8")).not.toMatch(/(?:repo|doc)\//);
    await initProject(home,{name:"source-repo",repository,contextPath:root,installRouting:false});
    expect((await validateProject(root)).filter(item=>item.level==="error")).toEqual([]);
    await writeFile(path.join(repository,"START_HERE.md"),"Read [.deep-context product](.deep-context/doc/PRODUCT.md).\n");
    await writeFile(contextAgents,(await readFile(contextAgents,"utf8"))+"\nStale route: `repo/docs/plan/STATUS.json`.\n");
    const stale=await validateProject(root);
    expect(stale.map(item=>item.code)).toEqual(expect.arrayContaining(["retired-source-startup-route","retired-startup-route"]));
  });
});
